"""Reproducible independent bud/fit-kit solid audit; run with FreeCAD Python.

Writes CAD-INTERFERENCE-AUDIT.txt beside the exported model. Does not modify
geometry. This verifies only the recorded CAD properties, not physical behavior.
"""
from pathlib import Path
import contextlib
import hashlib
import io
import itertools
import math
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import PARTS, moved
from earbuds import build_bud, build_fit_kit, fin_geometry, fin_contact_area, tip_geometry

ROOT = Path(__file__).resolve().parent.parent
THRESHOLD = 0.1


def name(part):
    return part['name'].split(' | ', 1)[-1]


def interface_note(a, b):
    pair = {name(a), name(b)}
    if pair == {'Tip retention bead', 'Medium removable silicone tip'}:
        return 'Flexible tip/retention interference concept; deformation and fit unvalidated.'
    if pair == {'Acoustic nozzle', 'Tip retention bead'}:
        return 'Bead/nozzle insert interface; production attachment detail unspecified.'
    if pair == {'Champagne seam rim', 'Housing perimeter gasket'}:
        return 'Cosmetic rim/seal interface; compression and tolerance unspecified.'
    if 'Cable strain relief' in pair and any(p.startswith('Strain relief groove') for p in pair):
        return 'Cosmetic relief detail overlaid on flexible boot.'
    if any(p.startswith('Fin connector contact') for p in pair):
        return 'Illustrative fin-contact insert; terminal seating and retention remain conceptual.'
    return None


def main():
    PARTS.clear()
    lines = [
        'INDEPENDENT EAR BUD / FIT-KIT CAD GEOMETRY AUDIT',
        'Units: millimetres, cubic millimetres. Pair reporting threshold: 0.1 mm3.',
        'This audit does not validate manufacturing, electrical behavior, anatomy or fit.',
        '',
        'SOURCE SNAPSHOT',
    ]
    for filename in ['common.py', 'earbuds.py']:
        digest = hashlib.sha256((ROOT / 'source' / filename).read_bytes()).hexdigest()
        lines.append(filename + ' SHA256: ' + digest)
    lines.extend(['', 'FIT INTERFACES'])
    failures = []
    for label, scale in [('S', .94), ('M', 1.), ('L', 1.10)]:
        fin, pad = fin_geometry(scale)
        support = moved(pad, (0, 0, -.8))
        fraction = support.common(fin).Volume / support.Volume
        lines.append(f'Fin {label}: pad support fraction {fraction:.12f}; '
                     f'fin/pad solids valid {fin.isValid()}/{pad.isValid()}; '
                     f'pad exposed curved face {fin_contact_area(scale):.9f} mm2.')
        if fraction < .999999 or not fin.isValid() or not pad.isValid():
            failures.append('Fin support/validity: ' + label)
    for diameter in [12., 13.2, 14.4, 15.6, 16.8]:
        tip, pads = tip_geometry(diameter / 2)
        overlap = pads[0].common(pads[1]).Volume
        distance = pads[0].distToShape(pads[1])[0]
        lines.append(f'Tip diameter {diameter:.1f}: signal sectors overlap {overlap:.12f} mm3; '
                     f'minimum geometric separation {distance:.6f} mm.')
        if overlap > 1e-8 or distance < 1e-5:
            failures.append('Tip signal separation: ' + str(diameter))
    with contextlib.redirect_stdout(io.StringIO()):
        build_bud('L')
        build_bud('R')
        build_fit_kit()
    invalid = [p['name'] for p in PARTS if p['shape'].isNull() or not p['shape'].isValid() or not p['shape'].Solids]
    failures += invalid
    left = [p for p in PARTS if p['group'] == 'Left earbud']
    right = [p for p in PARTS if p['group'] == 'Right earbud']
    delta = max(abs(a['shape'].Volume - b['shape'].Volume) for a, b in zip(left, right))
    lines.extend(['', 'VALIDITY AND MIRRORING',
                  f'Earbud objects: {len(left) + len(right)}; fit-kit objects: {len(PARTS)-len(left)-len(right)}.',
                  'Invalid/null/non-solid objects: ' + repr(invalid),
                  f'Maximum corresponding L/R solid volume difference: {delta:.12g} mm3.',
                  'Right-hand assembly is generated by mirroring the same source construction.',
                  '', 'RESIDUAL PAIRWISE COMMON VOLUMES ABOVE THRESHOLD',
                  'Tested all distinct left-earbud object pairs whose bounding boxes overlap.',
                  'Mirrored right-ear geometry shares the same source construction.',
                  'Fit-kit geometry was checked for validity and electrode isolation/support,',
                  'not spatial presentation-layout clashes. This audit does not cover the hub',
                  'or cable system, self-intersection within a compound, or assembly motion.'])
    found = []
    for a, b in itertools.combinations(left, 2):
        sa, sb = a['shape'], b['shape']
        if not sa.BoundBox.intersect(sb.BoundBox):
            continue
        volume = sa.common(sb).Volume
        if volume > THRESHOLD:
            found.append((volume, a, b, interface_note(a, b)))
    unresolved = []
    for volume, a, b, note in sorted(found, key=lambda x: -x[0]):
        pair_text = f'{volume:.6f} mm3 | {name(a)} <> {name(b)}'
        lines.append(pair_text)
        lines.append('  ' + (note or 'Unresolved component interference.'))
        if note is None:
            unresolved.append(pair_text)
    if not found:
        lines.append('None above threshold.')
    lines.extend(['', 'AUDIT RESULT',
                  f'Validity/support/isolation failures: {len(failures)}.',
                  f'Unclassified residual interferences above threshold: {len(unresolved)}.',
                  'Residual interface overlaps listed above are explicit conceptual assumptions;',
                  'they must not be interpreted as approved interference fits or solved assembly details.',
                  'Passing these checks does not establish a manufacturable or medically validated design.'])
    if failures:
        lines.extend(failures)
    (ROOT / 'CAD-INTERFERENCE-AUDIT.txt').write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))
    return len(failures) + len(unresolved)


if __name__ == '__main__':
    raise SystemExit(main())
