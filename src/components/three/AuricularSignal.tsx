function makeSurfaceNerves() {
  return SURFACE_NERVE_POINTS.map((points) => {
    const path = new THREE.CatmullRomCurve3(points.map((point) => new THREE.Vector3(...point)), false, "centripetal");
    path.arcLengthDivisions = 256;
    return new THREE.TubeGeometry(path, 96, 0.007, 8, false);
  });
}

function signalMaterial() {
  return new THREE.ShaderMaterial({
    transparent: true, depthTest: true, depthWrite: false, toneMapped: false,
    uniforms: { time: { value: 0 }, reveal: { value: 0 }, activity: { value: 0 } },
    vertexShader: `
      varying float vProgress;
      varying vec3 vNormal;
      void main() {
        vProgress = uv.x;
        vNormal = normalize(normalMatrix * normal);
        gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
      }
    `,
    fragmentShader: `
      uniform float time;
      uniform float reveal;
      uniform float activity;
      varying float vProgress;
      varying vec3 vNormal;
      void main() {
        float strength = pow(activity, 0.62);
        float phase = fract(vProgress * 0.74 - time * 0.32 + 0.5) - 0.5;
        float pulse = exp(-phase * phase * 108.0);
        float shade = 0.84 + 0.16 * abs(dot(normalize(vNormal), normalize(vec3(-0.4, 0.7, 0.8))));
        float crown = smoothstep(0.50, 0.95, vProgress);
        vec3 resting = mix(vec3(0.70, 0.035, 0.17), vec3(0.34, 0.055, 0.62), crown);
        vec3 lit = mix(vec3(0.98, 0.25, 0.42), vec3(0.84, 0.24, 0.96), crown);
        vec3 colour = mix(resting * shade, lit, strength * (0.18 + 0.78 * pulse));
        colour += vec3(0.10, 0.08, 0.10) * strength * pulse;
        float merge = 1.0 - smoothstep(0.76, 1.0, vProgress);
        gl_FragColor = vec4(colour, reveal * (0.28 + strength * 0.70) * merge);
        #include <colorspace_fragment>
      }
    `,
  });
}

/** Surface signal joins the concha to the neural tree above the glass cutaway. */
export function AuricularSignal({ reveal, stimulation }: {
  geometry: THREE.BufferGeometry;
  reveal: MotionValue<number>;
  stimulation: MotionValue<number>;
}) {
  const root = useRef<THREE.Group>(null);
  const nerves = useMemo(makeSurfaceNerves, []);
  const material = useMemo(signalMaterial, []);

  useEffect(() => () => { nerves.forEach((nerve) => nerve.dispose()); }, [nerves]);
  useEffect(() => () => material.dispose(), [material]);

  useFrame(({ clock }) => {
    const visibility = THREE.MathUtils.clamp(reveal.get(), 0, 1);
    if (root.current) root.current.visible = visibility > 0.002;
    material.uniforms.time.value = clock.elapsedTime;
    material.uniforms.reveal.value = visibility;
    material.uniforms.activity.value = THREE.MathUtils.clamp(stimulation.get(), 0, 1);
  });

  return <group ref={root} visible={false} dispose={null}>
    {nerves.map((nerve, index) => <mesh key={index} geometry={nerve} material={material} renderOrder={4} />)}
  </group>;
}
